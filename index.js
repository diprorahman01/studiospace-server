require('dotenv').config();
const dns=require('node:dns');
const express=require('express');
const cors=require('cors');
const {connectDB,getDB,closeDB}=require('./src/config/db');
const studioRoutes=require('./src/routes/studioRoutes');
const createStudioRoutes=require('./src/routes/createStudioRoutes');
const ownerStudioRoutes=require('./src/routes/ownerStudioRoutes');
const editStudioRoutes=require('./src/routes/editStudioRoutes');
const deleteStudioRoutes=require('./src/routes/deleteStudioRoutes');
const bookingRoutes=require('./src/routes/bookingRoutes');
const hostBookingRoutes=require('./src/routes/hostBookingRoutes');
const bookingEmailMiddleware=require('./src/middleware/bookingEmailMiddleware');
const hostAvailabilityRoutes=require('./src/routes/hostAvailabilityRoutes');
const bookingBlockGuard=require('./src/middleware/bookingBlockGuard');
const adminRoutes=require('./src/routes/adminRoutes');
const app=express(),PORT=process.env.PORT||5000;
const CLIENT_URL=process.env.CLIENT_URL||'http://localhost:3000';
if(process.env.NODE_ENV!=='production')dns.setServers(['8.8.8.8','1.1.1.1']);
app.use(cors({origin:CLIENT_URL,credentials:true}));
app.use(express.json({limit:'100kb'}));
app.get('/',(_req,res)=>res.send('StudioSpace API Server is Running!'));
app.get('/api/health',async(_req,res)=>{try{const db=getDB();await db.command({ping:1});res.status(200).json({success:true,message:'StudioSpace server and MongoDB are connected!',database:db.databaseName})}catch(e){console.error(e);res.status(503).json({success:false,message:'Database connection unavailable.'})}});
app.use('/api/studios',ownerStudioRoutes);
app.use('/api/studios',createStudioRoutes);
app.use('/api/studios',editStudioRoutes);
app.use('/api/studios',deleteStudioRoutes);
app.use('/api/studios',studioRoutes);
app.use('/api/bookings',(req,res,next)=>{if(['POST','PUT','PATCH','DELETE'].includes(req.method)&&req.headers.origin!==CLIENT_URL)return res.status(403).json({success:false,message:'Invalid request origin.'});next()});
app.use('/api/bookings',bookingEmailMiddleware);
app.use('/api/host',bookingEmailMiddleware);
app.use('/api/bookings',bookingBlockGuard);
app.use('/api/bookings',bookingRoutes);
app.use('/api/host',hostAvailabilityRoutes);
app.use('/api/host',hostBookingRoutes);
app.use('/api/admin',adminRoutes);
app.use('/api',(_req,res)=>res.status(404).json({success:false,message:'API route not found.'}));
app.use((error,_req,res,_next)=>{console.error('Server error:',error);res.status(500).json({success:false,message:'Internal server error.'})});
async function startServer(){try{const db=await connectDB();const existing=new Set((await db.listCollections({},{nameOnly:true}).toArray()).map(c=>c.name));for(const name of ['studios','bookings','studioBlocks'])if(!existing.has(name))await db.createCollection(name);
await db.collection('bookings').createIndex({studioId:1,date:1,status:1,startMinutes:1,endMinutes:1});await db.collection('studios').createIndex({ownerId:1,createdAt:-1});await db.collection('bookings').createIndex({studioId:1,createdAt:-1});await db.collection('studioBlocks').createIndex({studioId:1,date:1,startMinutes:1,endMinutes:1});
const server=app.listen(PORT,()=>{console.log(`Server running at http://localhost:${PORT}`);console.log('StudioSpace booking, host, admin and availability routes ready');console.log(process.env.RESEND_API_KEY&&process.env.EMAIL_FROM?'Booking email configured':'Booking email disabled')});let shuttingDown=false;async function shutdown(){if(shuttingDown)return;shuttingDown=true;server.close(async()=>{try{await closeDB()}catch(e){console.error(e)}process.exit(0)})}process.on('SIGINT',shutdown);process.on('SIGTERM',shutdown)}catch(e){console.error('Server startup failed:',e);try{await closeDB()}catch(err){console.error(err)}process.exit(1)}}
startServer();
